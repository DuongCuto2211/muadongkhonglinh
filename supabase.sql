-- Sổ lưu bút công khai: khách được đọc và thêm lời nhắn, không được sửa/xóa.

create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  name varchar(40) not null check (char_length(btrim(name)) between 1 and 40),
  message varchar(280) not null check (char_length(btrim(message)) between 1 and 280),
  created_at timestamptz not null default now()
);

alter table public.guestbook_entries enable row level security;

-- Chỉ cấp quyền cần thiết cho khách chưa đăng nhập.
revoke all on table public.guestbook_entries from anon, authenticated;
grant select, insert on table public.guestbook_entries to anon, authenticated;
grant usage, select on sequence public.guestbook_entries_id_seq to anon, authenticated;

-- Cho phép khách đọc danh sách lời nhắn công khai.
drop policy if exists "Anyone can read guestbook" on public.guestbook_entries;
create policy "Anyone can read guestbook"
on public.guestbook_entries
for select
to anon, authenticated
using (true);

-- Cho phép khách thêm lời nhắn hợp lệ.
drop policy if exists "Anyone can add guestbook entry" on public.guestbook_entries;
create policy "Anyone can add guestbook entry"
on public.guestbook_entries
for insert
to anon, authenticated
with check (
  char_length(btrim(name)) between 1 and 40
  and char_length(btrim(message)) between 1 and 280
);

-- Không tạo policy UPDATE hoặc DELETE: khách không thể sửa/xóa lời nhắn qua API.
